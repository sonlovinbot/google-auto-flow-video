export function i18n(key, values = {}) {
  let text = translations[state.currentLang]?.[key] ?? translations.en?.[key];
  if (text === undefined) return `[${key}]`;
  for (const name in values) {
    text = text.replaceAll(`{${name}}`, values[name]);
  }
  return text;
}
